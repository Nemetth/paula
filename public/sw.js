// Minimal service worker: caches the app shell so the installed PWA opens
// even with a flaky connection. All data lives in IndexedDB (see src/lib/db),
// which the browser persists independently of this cache.
const CACHE = "paula-shell-v1";
const SHELL = ["/", "/hoy", "/clientes", "/plata"];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(SHELL)).catch(() => {}),
  );
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))),
  );
  self.clients.claim();
});

self.addEventListener("fetch", (event) => {
  if (event.request.method !== "GET") return;
  event.respondWith(
    fetch(event.request)
      .then((response) => {
        const copy = response.clone();
        caches.open(CACHE).then((cache) => cache.put(event.request, copy));
        return response;
      })
      .catch(() => caches.match(event.request).then((res) => res ?? caches.match("/hoy"))),
  );
});
